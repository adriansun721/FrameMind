import { _electron as electron, expect, test } from "@playwright/test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createNode } from "./modeling-actions";

test("T05 locates model and solver failures, repairs them and retains historical results", async ({}, testInfo) => {
  test.setTimeout(60_000);
  const directory = await mkdtemp(join(tmpdir(), "framemind-t05-"));
  const environment = { ...process.env, FRAMEMIND_E2E_PROJECT_PATH: join(directory, "诊断修正.framemind") };
  delete environment.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ args: ["."], env: environment });
  try {
    const page = await app.firstWindow();
    await page.getByRole("button", { name: "运行分析" }).click();
    const diagnostics = page.getByRole("region", { name: "分析诊断" });
    await expect(diagnostics).toContainText("模型检查");
    await expect(diagnostics).toContainText("模型没有杆件");
    await createNode(page, ["0", "0", "0"]); await createNode(page, ["4", "0", "0"]);
    await page.getByRole("button", { name: "创建材料与截面" }).click();
    await page.getByRole("button", { name: "保存材料与截面" }).click();
    await page.getByRole("button", { name: "创建杆件" }).click();
    await page.getByRole("button", { name: "添加杆件" }).click();
    await page.getByRole("button", { name: "设置支座", exact: true }).click();
    for (const label of ["UX 平移", "UY 平移", "UZ 平移", "RX 转动", "RY 转动", "RZ 转动"]) await page.getByLabel(label).uncheck();
    await page.getByRole("button", { name: "添加支座" }).click();
    await page.getByRole("button", { name: "运行分析" }).click();
    await diagnostics.getByRole("button", { name: "定位 B1 · 约束自由度" }).click();
    const inspector = page.getByRole("region", { name: "对象属性" });
    for (const label of ["UX 平移", "UY 平移", "UZ 平移"]) await inspector.getByLabel(label).check();
    await inspector.getByRole("button", { name: "保存支座属性" }).click();
    await page.getByRole("button", { name: "运行分析" }).click();
    await expect(diagnostics).toContainText("方程求解");
    await expect(diagnostics).toContainText("主元");
    await expect(diagnostics).toContainText("不能据此确定唯一原因");
    await diagnostics.getByRole("button", { name: /定位 N\d · 约束自由度/ }).click();
    await expect(inspector.getByText("空间节点", { exact: true })).toBeVisible();
    await page.getByRole("region", { name: "项目树" }).getByRole("button", { name: "B1 · N1", exact: true }).click();
    for (const label of ["RX 转动", "RY 转动", "RZ 转动"]) await inspector.getByLabel(label).check();
    await inspector.getByRole("button", { name: "保存支座属性" }).click();
    await page.getByRole("button", { name: "创建荷载" }).click();
    await page.getByLabel("FY", { exact: true }).fill("5");
    await page.getByRole("button", { name: "添加节点荷载" }).click();
    await page.getByRole("region", { name: "项目树" }).getByRole("button", { name: "L1 · N2", exact: true }).click();
    await inspector.getByLabel("FY", { exact: true }).fill("6");
    await inspector.getByRole("button", { name: "保存荷载属性" }).click();
    await page.getByRole("button", { name: "运行分析" }).click();
    await expect(page.getByRole("status")).toContainText("分析完成");
    await expect(diagnostics).toHaveCount(0);
    await expect(page.getByText("反力 (0.000, -6.000, 0.000) kN", { exact: true })).toBeVisible();
    await createNode(page, ["8", "0", "0"]);
    await page.getByRole("button", { name: "运行分析" }).click();
    const cameraBefore = await page.getByLabel("三维模型视图").getAttribute("data-camera-state");
    await diagnostics.getByRole("button", { name: "定位 N3 · 连接关系" }).click();
    await expect(page.getByLabel("三维模型视图")).not.toHaveAttribute("data-camera-state", cameraBefore!);
    await expect(inspector.getByText("node_0003", { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 1480, height: 920 });
    await page.screenshot({ path: testInfo.outputPath("T05-isolated-node-desktop.png") });
    const pixels = await page.locator(".viewport canvas").screenshot();
    const brightPixels = await app.evaluate(({ nativeImage }, png) => {
      const bitmap = nativeImage.createFromBuffer(Buffer.from(png, "base64")).toBitmap();
      let count = 0;
      for (let index = 0; index < bitmap.length; index += 4) if (Math.max(bitmap[index], bitmap[index + 1], bitmap[index + 2]) > 110) count += 1;
      return count;
    }, pixels.toString("base64"));
    expect(brightPixels).toBeGreaterThan(100);
    await page.setViewportSize({ width: 1080, height: 680 });
    await page.screenshot({ path: testInfo.outputPath("T05-isolated-node-compact.png") });
    await page.getByRole("button", { name: "查看分析结果" }).click();
    await expect(page.getByText("反力 (0.000, -6.000, 0.000) kN", { exact: true })).toBeVisible();
    await expect(page.getByText(/R\d+ · 已过期/)).toBeVisible();
    await page.getByRole("button", { name: "文件", exact: true }).click();
    await page.getByRole("menuitem", { name: /保存项目/ }).click();
    await expect(page.getByRole("status")).toContainText("已保存");
    await page.getByRole("button", { name: "创建杆件" }).click();
    const dialog = page.getByRole("dialog", { name: "连接空间杆件" });
    await dialog.getByLabel("起点节点").selectOption("node_0002"); await dialog.getByLabel("终点节点").selectOption("node_0003");
    await dialog.getByRole("button", { name: "添加杆件" }).click();
    await page.getByRole("button", { name: "运行分析" }).click();
    await expect(page.getByRole("status")).toContainText("分析完成 · 3 个节点结果，2 根杆件结果");
    await expect(diagnostics).toHaveCount(0);
    await page.getByRole("button", { name: "文件", exact: true }).click();
    page.once("dialog", (prompt) => prompt.accept());
    await page.getByRole("menuitem", { name: /打开项目/ }).click();
    await expect(page.getByRole("status")).toContainText("已打开");
    await expect(page.getByText("反力 (0.000, -6.000, 0.000) kN", { exact: true })).toBeVisible();
    await expect(page.getByTestId("viewport-member-count")).toHaveText("1 根杆件");
  } finally {
    await app.close(); await rm(directory, { recursive: true, force: true });
  }
});
